#!/usr/bin/env python3
"""Generates src/claude_code_multi_account/nfc_tables.py (Unicode data for the bundled NFC).

Run with a Python build providing Unicode 16.0.0 (such as Python 3.14), from python:
  python3 tools/gen_nfc.py > src/claude_code_multi_account/nfc_tables.py
"""
import sys
import unicodedata as ud

decomp: dict[int, list[int]] = {}
ccc: dict[int, int] = {}
comp: dict[tuple[int, int], int] = {}
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF or 0xAC00 <= cp <= 0xD7A3:
        continue
    c = chr(cp)
    k = ud.combining(c)
    if k:
        ccc[cp] = k
    d = ud.decomposition(c)
    if d and not d.startswith("<"):
        parts = [int(x, 16) for x in d.split()]
        decomp[cp] = parts
        if len(parts) == 2 and ud.normalize("NFC", c) == c:
            comp[(parts[0], parts[1])] = cp

if ud.unidata_version != "16.0.0":
    sys.exit(f"need Unicode 16.0.0, this Python has {ud.unidata_version}")
out = [f'"""Code generated by tools/gen_nfc.py (Unicode {ud.unidata_version}); DO NOT EDIT."""', "",
       "# Single-step canonical decompositions.", "DECOMP: dict[int, tuple[int, ...]] = {"]
out += [f"    0x{cp:X}: ({', '.join('0x%X' % x for x in decomp[cp])},)," for cp in sorted(decomp)]
out += ["}", "", "# Non-zero canonical combining classes.", "CCC: dict[int, int] = {"]
out += [f"    0x{cp:X}: {ccc[cp]}," for cp in sorted(ccc)]
out += ["}", "", "# Primary composites of (first, second).", "COMP: dict[tuple[int, int], int] = {"]
out += [f"    (0x{a:X}, 0x{b:X}): 0x{comp[(a, b)]:X}," for a, b in sorted(comp)]
out += ["}", ""]
sys.stdout.write("\n".join(out))
