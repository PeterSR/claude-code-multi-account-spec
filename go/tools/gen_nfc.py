#!/usr/bin/env python3
"""Generates nfc_tables.go (Unicode data for the NFC implementation) from Python's unicodedata.

Use a Python build with Unicode 16.0.0 (such as Python 3.14).
Run from go: python3 tools/gen_nfc.py > nfc_tables.go
"""
import sys
import unicodedata as ud

if ud.unidata_version != '16.0.0':
    sys.exit('gen_nfc.py needs Python with Unicode 16.0.0 data, this one has %s' % ud.unidata_version)

decomp = {}
ccc = {}
comp = {}
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF or 0xAC00 <= cp <= 0xD7A3:
        continue
    c = chr(cp)
    k = ud.combining(c)
    if k:
        ccc[cp] = k
    d = ud.decomposition(c)
    if d and not d.startswith('<'):
        parts = [int(x, 16) for x in d.split()]
        decomp[cp] = parts
        # primary composite: two-part decomposition that is not a composition exclusion
        if len(parts) == 2 and ud.normalize('NFC', c) == c:
            comp[(parts[0], parts[1])] = cp

out = []
w = out.append
w('// Code generated by tools/gen_nfc.py (Unicode %s); DO NOT EDIT.\n' % ud.unidata_version)
w('package multiaccount\n')
w('// nfcDecomp maps a rune to its single-step canonical decomposition.')
w('var nfcDecomp = map[rune][]rune{')
for cp in sorted(decomp):
    w('\t0x%X: {%s},' % (cp, ', '.join('0x%X' % x for x in decomp[cp])))
w('}\n')
w('// nfcCCC maps a rune to its non-zero canonical combining class.')
w('var nfcCCC = map[rune]uint8{')
for cp in sorted(ccc):
    w('\t0x%X: %d,' % (cp, ccc[cp]))
w('}\n')
w('// nfcComp maps a (first, second) pair to its primary composite.')
w('var nfcComp = map[[2]rune]rune{')
for k in sorted(comp):
    w('\t{0x%X, 0x%X}: 0x%X,' % (k[0], k[1], comp[k]))
w('}')
sys.stdout.write('\n'.join(out) + '\n')
